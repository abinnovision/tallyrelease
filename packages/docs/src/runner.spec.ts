import { describe, expect, it } from "vitest";

import { run } from "./runner.ts";

import type { DocTarget } from "./runner.ts";

const root = "/repo";
const targets: DocTarget[] = [
	{ name: "a", path: "docs/a.md", render: () => "# A\n\nBody of a.\n" },
	{
		name: "b",
		path: "docs/b.md",
		render: () => Promise.resolve("# B\n\nBody of b.\n"),
	},
];

const memory = (files: Record<string, string> = {}) => {
	const store = new Map(Object.entries(files));

	return {
		store,
		read: (file: string) => store.get(file),
		write: (file: string, content: string) => store.set(file, content),
	};
};

describe("run", () => {
	it("writes formatted content with the generated header", async () => {
		const fs = memory();
		const stale = await run(targets, { root, check: false, ...fs });

		expect(stale).toEqual(["docs/a.md", "docs/b.md"]);
		expect(fs.store.get("/repo/docs/a.md")).toBe(
			"# A\n\n<!-- Generated by @internal/docs (target: a). Run `yarn fix` to update. -->\n\nBody of a.\n",
		);
	});

	it("returns every stale path in check mode and writes nothing", async () => {
		const fs = memory({ "/repo/docs/a.md": "# A\n" });
		const stale = await run(targets, { root, check: true, ...fs });

		expect(stale).toEqual(["docs/a.md", "docs/b.md"]);
		expect([...fs.store.keys()]).toEqual(["/repo/docs/a.md"]);
	});

	it("returns nothing for a fresh tree", async () => {
		const fs = memory();
		await run(targets, { root, check: false, ...fs });

		expect(await run(targets, { root, check: true, ...fs })).toEqual([]);
	});
});
