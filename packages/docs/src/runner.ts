import { format, resolveConfig } from "prettier";

const withHeader = (name: string, markdown: string): string => {
	const [title = "", ...rest] = markdown.split("\n");
	if (!title.startsWith("# ")) {
		throw new Error(`docs target ${name} must start with a "# " title line.`);
	}

	const header = `<!-- Generated by @internal/docs (target: ${name}). Run \`yarn fix\` to update. -->`;

	return [title, "", header, "", ...rest].join("\n");
};

export interface DocTarget {
	name: string;
	/** Output path relative to the repository root. */
	path: string;
	/** Markdown starting with a `# ` title line. */
	render: () => string | Promise<string>;
}

export interface RunOptions {
	root: string;
	check: boolean;
	read: (file: string) => string | undefined;
	write: (file: string, content: string) => void;
}

/**
 * Renders and formats every target, writing stale files unless `check` is set.
 * Returns the paths of stale targets.
 */
export const run = async (
	targets: DocTarget[],
	{ root, check, read, write }: RunOptions,
): Promise<string[]> => {
	const rendered = await Promise.all(
		targets.map(async (target) => {
			const file = `${root}/${target.path}`;
			const markdown = withHeader(target.name, await target.render());
			const options = { ...(await resolveConfig(file)), filepath: file };

			return {
				path: target.path,
				file,
				content: await format(markdown, options),
			};
		}),
	);

	const stale = rendered.filter(({ file, content }) => read(file) !== content);
	if (!check) {
		for (const { file, content } of stale) {
			write(file, content);
		}
	}

	return stale.map(({ path }) => path);
};
